"""Pydantic v2 data models for GENI (StockShield AI Analysis Assistant)."""

import re
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, field_validator


class MessageRole(str, Enum):
    """Role classification for conversation turns."""

    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM = "system"


class GeniChatRequest(BaseModel):
    """Inbound user question payload targeting a completed analysis run."""

    run_id: str = Field(
        ...,
        description="Canonical identifier of the completed StockShield analysis run",
        min_length=5,
        max_length=64,
        examples=["run_3be6e1bfc274"],
    )
    message: str = Field(
        ...,
        description="User question or clarification directive regarding the analysis",
        min_length=1,
        max_length=4000,
        examples=["Why is this stock classified as moderate risk despite a bullish technical signal?"],
    )
    conversation_id: Optional[str] = Field(
        default=None,
        description="Optional ID of an existing conversation thread to maintain multi-turn context",
        max_length=64,
        examples=["conv_89a1f2b3c4d5"],
    )

    @field_validator("run_id")
    @classmethod
    def validate_run_id_format(cls, v: str) -> str:
        cleaned = v.strip()
        if ".." in cleaned or "/" in cleaned or "\\" in cleaned:
            raise ValueError("Path traversal sequences are strictly disallowed in run_id.")
        if not re.match(r"^run_[a-zA-Z0-9_\-]+$", cleaned):
            raise ValueError(
                f"Invalid run_id format '{v}'. Expected alphanumeric pattern matching '^run_[a-zA-Z0-9_\\-]+$'."
            )
        return cleaned

    @field_validator("message")
    @classmethod
    def sanitize_user_message(cls, v: str) -> str:
        cleaned = v.strip()
        if not cleaned:
            raise ValueError("User message cannot be empty or solely whitespace.")
        disallowed_tags = ["<script", "javascript:", "data:text/html", "__import__"]
        lower = cleaned.lower()
        for tag in disallowed_tags:
            if tag in lower:
                raise ValueError(f"Disallowed script or payload expression detected in message: '{tag}'.")
        return cleaned

    @field_validator("conversation_id")
    @classmethod
    def validate_conversation_id_format(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return None
        cleaned = v.strip()
        if not cleaned:
            return None
        if ".." in cleaned or "/" in cleaned or "\\" in cleaned:
            raise ValueError("Path traversal sequences are strictly disallowed in conversation_id.")
        if not re.match(r"^conv_[a-zA-Z0-9_\-]+$", cleaned):
            raise ValueError(
                f"Invalid conversation_id format '{v}'. Expected alphanumeric pattern matching '^conv_[a-zA-Z0-9_\\-]+$'."
            )
        return cleaned


class GeniChatResponse(BaseModel):
    """Outbound grounded explanation response produced by GENI."""

    run_id: str = Field(..., description="Target analysis run identifier")
    conversation_id: str = Field(..., description="Persistent conversation thread identifier")
    assistant_name: str = Field(default="GENI", description="Assistant identity name")
    response: str = Field(..., description="Grounded natural language response generated by GENI")
    status: str = Field(default="success", description="Response status: success, rate_limited, error")
    sources_used: List[str] = Field(
        default_factory=list,
        description="Analysis domains referenced to construct the explanation",
        examples=[["technical_analysis", "risk_assessment", "forecasting"]],
    )
    trace_id: Optional[str] = Field(default=None, description="Observability trace identifier")
    created_at_utc: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    model_used: Optional[str] = Field(default=None, description="Actual Gemini model used to generate reply")
    error: Optional[str] = Field(default=None, description="Error message when status is non-success")


class GeniMessage(BaseModel):
    """Single persistent turn in a conversation thread."""

    message_id: str = Field(..., description="Unique message identifier")
    conversation_id: str = Field(..., description="Parent conversation identifier")
    role: MessageRole = Field(..., description="Message speaker role")
    content: str = Field(..., description="Message text content")
    sources_used: List[str] = Field(default_factory=list)
    created_at_utc: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    metadata: Dict[str, Any] = Field(default_factory=dict)


class GeniConversationInfo(BaseModel):
    """Metadata record for a conversation thread."""

    conversation_id: str
    run_id: str
    ticker: str
    created_at_utc: str
    updated_at_utc: str
    message_count: int = 0
